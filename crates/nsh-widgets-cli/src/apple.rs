//! Builds the WidgetKit extension (`NshWidgets.appex`) for the iOS simulator, iOS devices and macOS,
//! with swiftc and Apple's App Intents metadata processor: no Xcode project.

use std::{
    fmt::Write as _,
    fs,
    path::{Path, PathBuf},
    process::Command,
};

use anyhow::{Context as _, bail};
use serde_json::{Value, json};

use crate::config::{App, Config};

/// The renderer every extension compiles: it draws any Widget Tree IR v1 tree.
const RENDERER: &str = include_str!("../renderer/NshWidgets.swift");
/// The protocols App Intents metadata extraction looks for.
const PROTOCOLS: &str = r#"["AppIntent","EntityQuery","AppEntity","TransientEntity","AppEnum","AppShortcutProviding","AppShortcutsProvider","AnyResolverProviding","AppIntentsPackage","DynamicOptionsProvider","_IntentValueRepresentable","_AssistantIntentsProvider","_GenerativeFunctionExtractable","IntentValueQuery","Resolver","AppExtension","ExtensionPointDefining"]"#;
pub const MODULE: &str = "NshWidgets";

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Platform {
    Simulator,
    Device,
    Mac,
}

impl Platform {
    pub fn sdk(self) -> &'static str {
        match self {
            Platform::Simulator => "iphonesimulator",
            Platform::Device => "iphoneos",
            Platform::Mac => "macosx",
        }
    }

    fn triple(self, config: &Config) -> String {
        let t = &config.deployment_target;
        match self {
            Platform::Simulator => format!("arm64-apple-ios{}-simulator", t.ios),
            Platform::Device => format!("arm64-apple-ios{}", t.ios),
            Platform::Mac => format!("arm64-apple-macos{}", t.macos),
        }
    }

    /// Where the built extension goes, relative to the app.
    pub fn appex(self) -> PathBuf {
        PathBuf::from(".nsh-widgets")
            .join(self.sdk())
            .join(format!("{MODULE}.appex"))
    }
}

/// The WidgetBundle naming one generic widget per kind.
pub fn bundle_source(config: &Config) -> String {
    let mut out = String::from(
        "// Generated by nsh-widgets build from widgets.json. Do not edit.\nimport SwiftUI\nimport WidgetKit\n\n",
    );
    for (i, w) in config.widgets.iter().enumerate() {
        let families: Vec<String> = w
            .families
            .iter()
            .map(|f| {
                let name = match f.as_str() {
                    "small" => "systemSmall",
                    "large" => "systemLarge",
                    "extraLarge" => "systemExtraLarge",
                    _ => "systemMedium",
                };
                format!(".{name}")
            })
            .collect();
        let _ = writeln!(
            out,
            "struct NshKind{i}: Widget {{\n    var body: some WidgetConfiguration {{\n        nshUIConfiguration({}, {}, {}, [{}])\n    }}\n}}\n",
            swift_string(&w.kind),
            swift_string(&w.name),
            swift_string(&w.description),
            families.join(", ")
        );
    }
    // A WidgetBundle body takes at most ten widgets: group them by ten.
    let groups: Vec<Vec<usize>> = (0..config.widgets.len())
        .collect::<Vec<_>>()
        .chunks(10)
        .map(<[usize]>::to_vec)
        .collect();
    if groups.len() == 1 {
        out.push_str("@main\nstruct NshWidgetsBundle: WidgetBundle {\n    var body: some Widget {\n");
        for i in &groups[0] {
            let _ = writeln!(out, "        NshKind{i}()");
        }
        out.push_str("    }\n}\n");
    } else {
        for (g, kinds) in groups.iter().enumerate() {
            let _ = writeln!(
                out,
                "struct NshKindGroup{g}: WidgetBundle {{\n    var body: some Widget {{"
            );
            for i in kinds {
                let _ = writeln!(out, "        NshKind{i}()");
            }
            out.push_str("    }\n}\n\n");
        }
        out.push_str("@main\nstruct NshWidgetsBundle: WidgetBundle {\n    var body: some Widget {\n");
        for g in 0..groups.len() {
            let _ = writeln!(out, "        NshKindGroup{g}().body");
        }
        out.push_str("    }\n}\n");
    }
    out
}

fn swift_string(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// The extension's Info.plist.
pub fn info_plist(platform: Platform, app: &App, config: &Config, fonts: &[String]) -> Value {
    let mut info = json!({
        "CFBundleDevelopmentRegion": "en",
        "CFBundleDisplayName": format!("{} Widgets", app.name),
        "CFBundleExecutable": MODULE,
        "CFBundleIdentifier": format!("{}.widgets", app.id),
        "CFBundleInfoDictionaryVersion": "6.0",
        "CFBundleName": MODULE,
        "CFBundlePackageType": "XPC!",
        "CFBundleShortVersionString": app.version,
        "CFBundleVersion": app.build,
        "NSExtension": { "NSExtensionPointIdentifier": "com.apple.widgetkit-extension" },
    });
    let map = info.as_object_mut().expect("object");
    match platform {
        Platform::Mac => {
            map.insert("CFBundleSupportedPlatforms".into(), json!(["MacOSX"]));
            map.insert("LSMinimumSystemVersion".into(), json!(config.deployment_target.macos));
            map.insert("NshWidgetsAppGroup".into(), json!(config.macos_group()));
            if !fonts.is_empty() {
                map.insert("ATSApplicationFontsPath".into(), json!("."));
            }
        }
        _ => {
            let sdk = if platform == Platform::Simulator {
                "iPhoneSimulator"
            } else {
                "iPhoneOS"
            };
            map.insert("CFBundleSupportedPlatforms".into(), json!([sdk]));
            map.insert("MinimumOSVersion".into(), json!(config.deployment_target.ios));
            map.insert("UIDeviceFamily".into(), json!([1, 2]));
            map.insert("NshWidgetsAppGroup".into(), json!(config.app_group));
            if !fonts.is_empty() {
                map.insert("UIAppFonts".into(), json!(fonts));
            }
        }
    }
    info
}

/// An XML property list of a JSON value (objects, arrays, strings, numbers, booleans).
pub fn plist(value: &Value) -> String {
    fn esc(s: &str) -> String {
        s.replace('&', "&amp;").replace('<', "&lt;").replace('>', "&gt;")
    }
    fn write(v: &Value, depth: usize, out: &mut String) {
        let pad = "  ".repeat(depth);
        match v {
            Value::Object(m) => {
                let _ = writeln!(out, "{pad}<dict>");
                for (k, v) in m {
                    let _ = writeln!(out, "{pad}  <key>{}</key>", esc(k));
                    write(v, depth + 1, out);
                }
                let _ = writeln!(out, "{pad}</dict>");
            }
            Value::Array(a) => {
                let _ = writeln!(out, "{pad}<array>");
                for v in a {
                    write(v, depth + 1, out);
                }
                let _ = writeln!(out, "{pad}</array>");
            }
            Value::String(s) => {
                let _ = writeln!(out, "{pad}<string>{}</string>", esc(s));
            }
            Value::Bool(b) => {
                let _ = writeln!(out, "{pad}<{b}/>");
            }
            Value::Number(n) if n.is_i64() || n.is_u64() => {
                let _ = writeln!(out, "{pad}<integer>{n}</integer>");
            }
            Value::Number(n) => {
                let _ = writeln!(out, "{pad}<real>{n}</real>");
            }
            Value::Null => {}
        }
    }
    let mut out = String::from(
        "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<!DOCTYPE plist PUBLIC \"-//Apple//DTD PLIST 1.0//EN\" \"http://www.apple.com/DTDs/PropertyList-1.0.dtd\">\n<plist version=\"1.0\">\n",
    );
    write(value, 0, &mut out);
    out.push_str("</plist>\n");
    out
}

fn run(cmd: &mut Command, what: &str) -> anyhow::Result<String> {
    let out = cmd.output().with_context(|| format!("run {what}"))?;
    if !out.status.success() {
        bail!(
            "{what} failed:\n{}{}",
            String::from_utf8_lossy(&out.stdout),
            String::from_utf8_lossy(&out.stderr)
        );
    }
    Ok(String::from_utf8_lossy(&out.stdout).trim().to_owned())
}

/// Xcode's build version (for example 27A266a), which the metadata processor asks for.
fn xcode_build() -> anyhow::Result<String> {
    let v = run(Command::new("xcodebuild").arg("-version"), "xcodebuild -version")?;
    v.lines()
        .find_map(|l| l.strip_prefix("Build version ").map(str::to_owned))
        .context("xcodebuild -version printed no build version")
}

/// Builds the extension for `platform` into `<app>/.nsh-widgets/<sdk>/NshWidgets.appex`.
pub fn build(app_dir: &Path, app: &App, config: &Config, platform: Platform) -> anyhow::Result<PathBuf> {
    let sdk = platform.sdk();
    let work = app_dir.join(".nsh-widgets/work").join(sdk);
    let appex = app_dir.join(platform.appex());
    let _ = fs::remove_dir_all(&work);
    let _ = fs::remove_dir_all(&appex);
    fs::create_dir_all(&work)?;
    let (exe_dir, res_dir, plist_path) = if platform == Platform::Mac {
        let c = appex.join("Contents");
        (c.join("MacOS"), c.join("Resources"), c.join("Info.plist"))
    } else {
        (appex.clone(), appex.clone(), appex.join("Info.plist"))
    };
    fs::create_dir_all(&exe_dir)?;
    fs::create_dir_all(&res_dir)?;

    let renderer = work.join("NshWidgets.swift");
    let bundle = work.join("Bundle.swift");
    fs::write(&renderer, RENDERER)?;
    fs::write(&bundle, bundle_source(config))?;
    fs::write(work.join("protocols.json"), PROTOCOLS)?;

    let sdk_path = run(
        Command::new("xcrun").args(["--sdk", sdk, "--show-sdk-path"]),
        "xcrun --show-sdk-path",
    )?;
    let triple = platform.triple(config);
    let exe = exe_dir.join(MODULE);
    let constvals = work.join(format!("{MODULE}.swiftconstvalues"));
    run(
        Command::new("xcrun")
            .args([
                "--sdk",
                sdk,
                "swiftc",
                "-parse-as-library",
                "-application-extension",
                "-O",
                "-swift-version",
                "5",
                "-wmo",
            ])
            .args(["-target", &triple, "-sdk", &sdk_path, "-module-name", MODULE])
            .arg("-emit-const-values-path")
            .arg(&constvals)
            .args(["-Xfrontend", "-const-gather-protocols-file", "-Xfrontend"])
            .arg(work.join("protocols.json"))
            // Without this entry point the extension crashes in Apple's extension bootstrap.
            .args([
                "-Xlinker",
                "-e",
                "-Xlinker",
                "_NSExtensionMain",
                "-framework",
                "Foundation",
                "-o",
            ])
            .arg(&exe)
            .arg(&renderer)
            .arg(&bundle),
        "swiftc",
    )?;

    // App Intents metadata: without it a widget button fails with "There is no metadata".
    fs::write(
        work.join("sources.txt"),
        format!("{}\n{}\n", renderer.display(), bundle.display()),
    )?;
    fs::write(work.join("constvals.txt"), format!("{}\n", constvals.display()))?;
    let swiftc = PathBuf::from(run(
        Command::new("xcrun").args(["--find", "swiftc"]),
        "xcrun --find swiftc",
    )?);
    let toolchain = swiftc.ancestors().nth(3).context("swiftc's toolchain")?.to_path_buf();
    let (family, target) = if platform == Platform::Mac {
        ("macOS", &config.deployment_target.macos)
    } else {
        ("iOS", &config.deployment_target.ios)
    };
    run(
        Command::new("xcrun")
            .arg("appintentsmetadataprocessor")
            .arg("--toolchain-dir")
            .arg(&toolchain)
            .args(["--module-name", MODULE, "--output"])
            .arg(&res_dir)
            .args([
                "--sdk-root",
                &sdk_path,
                "--xcode-version",
                &xcode_build()?,
                "--platform-family",
                family,
            ])
            .args([
                "--deployment-target",
                target,
                "--target-triple",
                &triple,
                "--source-file-list",
            ])
            .arg(work.join("sources.txt"))
            .arg("--swift-const-vals-list")
            .arg(work.join("constvals.txt"))
            .arg("--binary-file")
            .arg(&exe)
            .args(["--compile-time-extraction", "--force"]),
        "appintentsmetadataprocessor",
    )?;
    if !res_dir.join("Metadata.appintents").exists() {
        bail!(
            "appintentsmetadataprocessor wrote no Metadata.appintents into {}",
            res_dir.display()
        );
    }

    let mut fonts = Vec::new();
    for font in &config.fonts {
        let src = app_dir.join(font);
        let name = font
            .file_name()
            .context("font file name")?
            .to_string_lossy()
            .into_owned();
        fs::copy(&src, res_dir.join(&name)).with_context(|| format!("copy font {}", src.display()))?;
        fonts.push(name);
    }
    fs::write(&plist_path, plist(&info_plist(platform, app, config, &fonts)))?;
    Ok(appex)
}
